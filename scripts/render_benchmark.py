"""Generate BENCHMARK.md from the committed results files (docs/PLAN.md, M5.7). Every number comes from:
results/m5/test_summary.json, results/m5/judge_summary.json, results/m5/judge_handcheck_scores.json,
results/m5/frozen_settings.json, results/m5/TEST_RUN.lock, results/m5/generation_test_*.jsonl,
results/m1/generation_dev.json, results/m4/generation_dev.json, results/m4/graph_report.md inputs and
results/spend/openrouter_calls.jsonl. Plain ASCII (accented names in examples are transliterated)."""

import json
import random
import unicodedata
from collections import Counter

from graphrag.config import ROOT
from graphrag.eval.answers import score
from graphrag.eval.bootstrap import paired_diff_ci

SYSTEMS = ["closed_book", "hybrid", "graph_only", "graph_plus_chunks_g0.5", "graph_plus_chunks_g0.5_no_exact_title"]
TYPES = ["comparison", "inference", "compositional", "bridge_comparison"]
GRAPHRAG = "graph_plus_chunks_g0.5"
N_EXAMPLES = 2      # per failure class
SEED = 42


def load(path):
    return json.loads((ROOT / path).read_text(encoding="utf-8"))


def read_jsonl(path):
    return [json.loads(line) for line in (ROOT / path).read_text(encoding="utf-8").splitlines()]


DASHES = dict.fromkeys(map(ord, "\u2010\u2011\u2012\u2013\u2014\u2015\u2212"), "-")


def ascii_text(s: str) -> str:
    """Plain ASCII for the report: Unicode dashes become "-", accents are dropped."""
    return unicodedata.normalize("NFKD", s.translate(DASHES)).encode("ascii", "ignore").decode("ascii")


def f2(x):
    return "-" if x is None else f"{x:.2f}"


def ci(m, signed=False):
    fmt = "{:+.3f}" if signed else "{:.2f}"
    return f"{fmt.format(m['mean'])} [{fmt.format(m['ci_low'])}, {fmt.format(m['ci_high'])}]"


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    return "\n".join(out + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def failure_class(r: dict) -> str:
    where = "all gold paragraphs in context" if r["all_gold_in_context"] else "a gold paragraph missing from context"
    return f"{'abstained' if r['unknown'] else 'answered wrong'}, {where}"


def render() -> str:
    t = load("results/m5/test_summary.json")
    j = load("results/m5/judge_summary.json")
    hc = load("results/m5/judge_handcheck_scores.json")
    fs = load("results/m5/frozen_settings.json")
    lock = load("results/m5/TEST_RUN.lock")
    dev1, dev4 = load("results/m1/generation_dev.json"), load("results/m4/generation_dev.json")
    rows = {n: read_jsonl(f"results/m5/generation_test_{n}.jsonl") for n in SYSTEMS}
    ledger = read_jsonl("results/spend/openrouter_calls.jsonl")
    p = t["primary_result"]
    sec = t["secondary_results"]

    lines = [
        "# GraphRAG Engine: test benchmark",
        "",
        "Generated by `scripts/render_benchmark.py` from the committed results files; no number is typed by hand.",
        "",
        "## Contents",
        "",
        "1. Setup",
        "2. Primary result",
        "3. Results per system and question type",
        "4. Secondary comparisons and the exact-title ablation",
        "5. Retrieval",
        "6. LLM judge and its hand check",
        "7. Dev vs test",
        "8. Error analysis",
        "9. Limitations and cost",
        "",
        "## 1. Setup",
        "",
        f"- Test split: {p['questions']} questions from the 2WikiMultihopQA validation split (300 multi-hop, 75 per "
        "type, and 75 single-hop), answered against a pooled corpus of gold and distractor paragraphs.",
        f"- Run once, at git tag `{fs['tag']}` (commit {fs['commit'][:7]}), settings hash {fs['settings_hash'][:12]}; "
        f"run-once lock `results/m5/TEST_RUN.lock`: {lock['status']} ({lock['started_at']} to {lock['finished_at']}).",
        "- All choices (retrieval configuration, entity resolution threshold, graph share) were made on the dev split; "
        "the test split was not used before this run.",
        f"- Generator: `{fs['generation']['model']}` on OpenRouter endpoint `{fs['generation']['endpoint']}`, temperature "
        f"{fs['generation']['temperature']}, reasoning effort {fs['generation']['reasoning_effort']}, "
        f"{fs['generation']['budget_tokens']}-token context. Every system may answer \"unknown\" (scores 0).",
        f"- Hybrid baseline: BM25 + `{fs['hybrid']['embedding_model']}`, weighted fusion alpha {fs['hybrid']['alpha']} "
        f"(title {'on' if fs['hybrid']['with_title'] else 'off'}), `{fs['hybrid']['reranker_model']}` reranker.",
        f"- Graph: entity and relation extraction, entity resolution, Neo4j graph; graph retrieval with at most "
        f"{fs['graph']['MAX_SEEDS']} seeds, 2 hops, hubs above degree {fs['graph']['HUB_DEGREE']} never passed through, "
        f"top {fs['graph']['TOP_PATHS']} paths; graph share g = {fs['graph']['g']} in `graph_plus_chunks_g0.5`.",
        f"- Scoring: {fs['scoring']['answers']}; 95% percentile bootstrap CIs ({fs['scoring']['bootstrap']['resamples']:,} "
        "resamples, seed 0); paired bootstrap for differences.",
        "",
        "## 2. Primary result",
        "",
        f"The one primary result, fixed before the run: the paired EM difference of `{GRAPHRAG}` vs `hybrid` over all "
        f"{p['questions']} test questions.",
        "",
        table(["Comparison", "Questions", "Paired EM difference [95% CI]"],
              [[p["comparison"], p["paired_em_difference"]["n"], ci(p["paired_em_difference"], True)]]),
        "",
        f"Pre-registered expectation: {p['pre_registered_expectation']}. Result: "
        f"{'met' if p['expectation_met'] else 'not met'}.",
        "",
        f"Pre-specified secondary result, questions the closed-book model gets wrong (n = "
        f"{sec['closed_book_wrong_subset']['n']}): {ci(sec['closed_book_wrong_subset']['paired_em_difference'], True)}.",
        "",
        "## 3. Results per system and question type",
        "",
        "EM [95% CI], unknown rate, and EM on answered questions. Test split.",
        "",
    ]
    res_rows = []
    for n in SYSTEMS:
        for g in ["all", "multi_hop", "single_hop"] + TYPES:
            m = t["systems"][n]["all_questions"][g]
            res_rows.append([n, g, m["em"]["n"], ci(m["em"]), f2(m["f1"]["mean"]), f2(m["unknown_rate"]),
                             m["answered"]["n"], f2(m["answered"]["em"])])
    lines += [table(["System", "Questions", "n", "EM [95% CI]", "F1", "Unknown rate", "Answered", "EM on answered"], res_rows), ""]
    cbw = [[n, ci(t["systems"][n]["closed_book_wrong"]["all"]["em"])] for n in SYSTEMS]
    lines += [f"Closed-book-wrong subset (n = {sec['closed_book_wrong_subset']['n']}), EM [95% CI]:", "",
              table(["System", "EM [95% CI]"], cbw), ""]

    lines += ["## 4. Secondary comparisons and the exact-title ablation", "",
              "Exploratory: several comparisons, no correction for multiple testing.", "",
              table(["Comparison", "Paired EM difference [95% CI]"],
                    [[k, ci(v, True)] for k, v in sec["exploratory"].items()]), ""]

    lines += ["## 5. Retrieval", "",
              "Multi-hop questions. All gold in context: every gold paragraph is in the packed context. Bridge entity "
              "recall: the paragraph of the bridge entity (the object of one gold triple that is the subject of another) "
              "is in the packed context.", "",
              table(["System", "All gold in context", "Bridge entity recall"],
                    [[n, f2(r["multi_hop_all_gold_in_context"]), f2(r["bridge_entity_recall"])] for n, r in t["retrieval"].items()]), ""]

    jd = j["judge"]
    lines += ["## 6. LLM judge and its hand check", "",
              f"- Judge: `{jd['model']}` on OpenRouter endpoint `{jd['endpoint']}` (a different model family than the generator), "
              f"temperature {jd['temperature']}, blind to the system. \"unknown\" answers count as incorrect without a judge call "
              f"({j['items']['unknown_answers_not_judged']} of {j['items']['test_answers']}); {j['items']['unique_items_judged']} unique "
              f"(question, answer) items judged: " + ", ".join(f"{v} {k}" for k, v in sorted(j['items']['verdicts'].items())) + ".",
              f"- Hand check: {hc['agreement']} of {hc['items']} judge verdicts agree with the hand grades "
              f"({hc['agreement_rate']:.2f}); {hc['labelling'][0].lower() + hc['labelling'][1:]}",
              "- Per stratum: " + "; ".join(f"{k} {v['agree']} of {v['items']}" for k, v in hc["by_stratum"].items()) + ".",
              *[f"- Disagreement, item {d['n']} ({d['stratum']}): judge said {d['judge']} (\"{d['judge_reason']}\"); "
                f"hand grade: {ascii_text(d['hand'])}." for d in hc["disagreements"]],
              "", "Judge accuracy (\"correct\" verdicts; unknown and unsure count as incorrect), all test questions:", "",
              table(["System", "Judge accuracy [95% CI]", "EM [95% CI]"],
                    [[n, ci(j["systems"][n]["groups"]["all"]["judge_accuracy"]), ci(t["systems"][n]["all_questions"]["all"]["em"])]
                     for n in SYSTEMS]), "",
              f"The primary comparison on the judge metric (secondary; EM stays primary): "
              f"{ci(j['primary_comparison_on_judge_metric']['paired_difference'], True)}.", ""]

    dev_src = {"closed_book": dev1, "hybrid": dev1}
    dev_src.update({n: dev4 for n in SYSTEMS if n not in dev_src})
    dv = [[n, ci(dev_src[n]["systems"][n]["all_questions"]["all"]["em"]), ci(t["systems"][n]["all_questions"]["all"]["em"])]
          for n in SYSTEMS]
    lines += ["## 7. Dev vs test", "",
              "EM on all questions. Dev has 125 questions and was used for every choice; test has 375 and was run once.", "",
              table(["System", "Dev EM [95% CI]", "Test EM [95% CI]"], dv), ""]

    fails = [r for r in rows[GRAPHRAG] if r["em"] == 0.0]
    classes = Counter(failure_class(r) for r in fails)
    aliases = load("data/answer_aliases.json")
    dash_only = {n: sum(1 for r in rs if r["em"] == 0.0 and not r["unknown"]
                        and score(r["prediction"].translate(DASHES), aliases[r["id"]])["em"] == 1.0)
                 for n, rs in rows.items()}

    def em_dash(r):
        return score(r["prediction"].translate(DASHES), aliases[r["id"]])["em"] if not r["unknown"] else 0.0

    hyb_by_id = {r["id"]: r for r in rows["hybrid"]}
    dash_primary = paired_diff_ci([em_dash(r) for r in rows[GRAPHRAG]], [em_dash(hyb_by_id[r["id"]]) for r in rows[GRAPHRAG]])
    rng = random.Random(f"{SEED}:benchmark-errors")
    lines += ["## 8. Error analysis", "",
              f"Every `{GRAPHRAG}` test answer with EM 0 ({len(fails)} of {len(rows[GRAPHRAG])}), classified from recorded "
              "facts only: whether the system abstained, and whether all gold paragraphs were in its context. "
              "Some EM-0 answers are correct under another wording (section 6).", "",
              table(["Failure class", "Answers"], [[k, v] for k, v in classes.most_common()]), "",
              f"Of these, {dash_only[GRAPHRAG]} answers differ from an accepted answer only by a Unicode dash (for example a "
              "non-breaking hyphen in \"Mecklenburg-Schwerin\"): the official 2Wiki normaliser removes only ASCII "
              "punctuation, so they score EM 0. Scoring is left as the official script defines it. Such answers per "
              "system: " + ", ".join(f"{n} {v}" for n, v in dash_only.items()) + f". Side check only (not the "
              f"primary result): with Unicode dashes normalised, the primary paired EM difference would be "
              f"{ci(dash_primary, True)}.", "",
              f"Seeded examples ({N_EXAMPLES} per class):", ""]
    for cls, _ in classes.most_common():
        pool = sorted((r for r in fails if failure_class(r) == cls), key=lambda r: r["id"])
        for r in rng.sample(pool, min(N_EXAMPLES, len(pool))):
            lines.append(f"- [{cls}] ({r['type']}) {ascii_text(r['question'])} Gold: {ascii_text(r['answer'])}. "
                         f"Answer: {ascii_text(r['prediction'])}.")
    lines.append("")

    spent = sum(r["cost_usd"] for r in ledger)
    lines += ["## 9. Limitations and cost", "",
              "- Pooled corpus: questions are answered against one corpus of gold and distractor paragraphs, unlike the "
              "standard 2Wiki distractor setting, so absolute numbers are not comparable with published leaderboards; the "
              "answer scoring is the official one.",
              "- The same model (gpt-oss-120b) extracts the knowledge graph and answers the questions; its extraction and "
              "answering errors may be correlated. The judge is a different model family.",
              "- The language models have likely seen Wikipedia; the closed-book baseline and the closed-book-wrong subset "
              "account for that, and the gains hold on that subset (section 2).",
              "- Single-hop questions are generated from templates, which favours lexical retrieval; the regenerated "
              "single-hop set was not hand-checked a second time.",
              "- Some 2Wiki gold triples link a mention to the wrong same-name page (found during entity resolution), and "
              "some single-hop questions are scored against the gold answer only, without aliases.",
              "- Entity resolution keeps precision first: some duplicates remain (for example United States in two "
              "clusters), see `results/m3/resolution_report.md`.",
              "- \"unknown\" scores 0. On two-way comparison questions a guess would often be right, so abstaining systems "
              "can score below guessing ones; the unknown rate is reported for every system.",
              "- Per-type results rest on 75 test questions each; secondary comparisons are exploratory.",
              "- EM follows the official 2Wiki normaliser, which keeps Unicode dashes; a few correct answers written with a "
              "non-breaking hyphen score EM 0 (section 8). The judge counts them correct.",
              f"- Judge: agreement with the hand check {hc['agreement']} of {hc['items']}; the hand-check first pass was "
              "drafted by Claude, a different model from the judge and the generator, and reviewed by hand.",
              f"- Cost: the test run {t['spend']['this_run_usd']:.3f} USD, the judge {j['calls']['cost_usd']:.3f} USD; all OpenRouter "
              f"calls of the project {spent:.2f} USD ({len(ledger):,} calls, `results/spend/openrouter_calls.jsonl`).",
              "",
              "---",
              "",
              "Rohith Kumar Reddipogula, 2026. MIT License.",
              ""]
    return ascii_text("\n".join(lines))


if __name__ == "__main__":
    (ROOT / "BENCHMARK.md").write_text(render(), encoding="utf-8")
    print("wrote BENCHMARK.md")
