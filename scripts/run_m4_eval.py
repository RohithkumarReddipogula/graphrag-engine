"""M4 dev evaluation (docs/PLAN.md, M4.3 and M4.4, approved 2026-10-09).

Systems on the 125 dev questions: closed_book and hybrid (reused from results/m1/, not re-run),
graph_only, graph_plus_chunks at g in {0.25, 0.5}; g is chosen by the fixed rule (highest multi-hop EM,
ties by multi-hop all-gold-in-context, then 0.25); then the ablation without EXACT_TITLE edges at that g.
Same generator, prompt, 1,500-token budget and abstention as M1. Test questions are never read.

Writes results/m4/generation_dev_<system>.jsonl, results/m4/graph_retrieval_dev.jsonl,
results/m4/generation_dev.json and results/m4/graph_report.md.
"""

import json
import logging
import time
from concurrent.futures import ThreadPoolExecutor

import numpy as np

from graphrag.config import get_settings
from graphrag.embed import E5Encoder
from graphrag.eval.answers import score
from graphrag.eval.bootstrap import mean_ci, paired_diff_ci
from graphrag.eval.report import build_summary
from graphrag.generation import PackedContext, build_prompt, pack_context, parse_answer
from graphrag.graph.retrieve import GraphIndex, graph_context, score_paths
from graphrag.graph.store import fetch_graph
from graphrag.llm.client import make_llm
from graphrag.llm.spend import ledger_totals, write_balance
from graphrag.resolution.embed_mentions import embed_mentions
from graphrag.resolution.mentions import build_mentions, norm_name
from graphrag.retrieval.base import Passage
from graphrag.retrieval.hybrid import CrossEncoderReranker, HybridConfig, HybridRetriever
from graphrag.store.corpus_store import fetch_chunks, vector_search
from graphrag.store.neo4j_client import connect

logging.getLogger("neo4j").setLevel(logging.ERROR)
BUDGET = 1500
G_OPTIONS = [0.25, 0.5]
WORKERS = 8
BAR = {"retrieval_gain_min": 0.10, "paired_em_ci_low_min": -0.05}
TARGET_TYPES = ("bridge_comparison", "compositional")


def read_jsonl(path):
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines()]


def write_jsonl(path, rows):
    with path.open("w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")


def bridge_chunks(q: dict, corpus: dict) -> set[str]:
    """Gold paragraphs of bridge entities: objects of one gold triple that are the subject of another."""
    subjects = {norm_name(s) for s, _, _ in q["evidences"]}
    bridges = {norm_name(o) for _, _, o in q["evidences"]} & subjects
    return {c for c in q["gold_chunk_ids"] if norm_name(corpus[c]["title"]) in bridges}


def combine(graph_part: PackedContext, passages: list[Passage], budget: int) -> PackedContext:
    rest = [p for p in passages if p.chunk_id not in set(graph_part.chunk_ids)]
    chunk_part = pack_context(rest, budget - graph_part.tokens)
    text = "\n\n".join(t for t in (graph_part.text, chunk_part.text) if t)
    return PackedContext(text=text, chunk_ids=graph_part.chunk_ids + chunk_part.chunk_ids,
                         tokens=graph_part.tokens + chunk_part.tokens)


def render_report(summary: dict) -> str:
    """Markdown report generated from results/m4/generation_dev.json (all numbers come from that file)."""
    bar, sel, ret = summary["quality_bar"], summary["g_selection"], summary["retrieval"]
    yes = lambda b: "yes" if b else "no"
    ci = lambda m: f"{m['mean']:.2f} [{m['ci_low']:.2f}, {m['ci_high']:.2f}]"
    lines = [
        "# M4 graph retrieval report (dev split)",
        "",
        "Generated by `scripts/run_m4_eval.py` from `results/m4/generation_dev.json`. Dev questions only (100",
        "multi-hop, 25 single-hop); test questions were never used. Dev numbers were used for choices (g), so",
        "they are optimistic; M5 on test is the real estimate. closed_book and hybrid are the M1 runs.",
        "",
        "## Quality bar (fixed in docs/PLAN.md before any M4 result)",
        "",
        f"Judged for `{bar['system']}` (g chosen by the fixed rule: {sel['rule']}).",
        "",
        "| Criterion | Result | Bar | Pass |",
        "|---|---|---|---|",
        f"| 1. Multi-hop all-gold-in-context gain over hybrid | {bar['1_retrieval_gain']['value']:+.2f} | at least +{bar['1_retrieval_gain']['min']:.2f} | {yes(bar['1_retrieval_gain']['pass'])} |",
        f"| 2. Paired EM difference vs hybrid, all 125 (95% CI) | {ci(bar['2_no_qa_regression']['paired_em_diff'])} | CI low at least {bar['2_no_qa_regression']['ci_low_min']:.2f} | {yes(bar['2_no_qa_regression']['pass'])} |",
        f"| 3. EM on bridge_comparison + compositional (n = {bar['3_target_types_gain']['n']}) | {bar['3_target_types_gain']['em_graph']:.2f} vs hybrid {bar['3_target_types_gain']['em_hybrid']:.2f} | above hybrid | {yes(bar['3_target_types_gain']['pass'])} |",
        "",
        f"All three pass: {yes(bar['all_pass'])}.",
        "",
        "## Retrieval",
        "",
        "| System | Multi-hop all gold in context | Bridge entity recall | Bridge questions |",
        "|---|---|---|---|",
        *[f"| {n} | {r['multi_hop_all_gold_in_context']:.2f} | {r['bridge_entity_recall']:.2f} | {r['bridge_questions']} |" for n, r in ret.items()],
        "",
        "## QA (EM with 95% CI; unknown rate; EM on answered questions)",
        "",
        "| System | Questions | n | EM [95% CI] | Unknown rate | EM on answered | Paired EM diff vs hybrid |",
        "|---|---|---|---|---|---|---|",
    ]
    for name, e in summary["systems"].items():
        for group in ("multi_hop", "single_hop", "all", "bridge_comparison", "compositional", "inference", "comparison"):
            m = e["all_questions"].get(group)
            if not m:
                continue
            pd = e.get("paired_diff_vs_hybrid_em") if group == "all" else None
            ans = m["answered"]["em"]
            lines.append(f"| {name} | {group} | {m['em']['n']} | {ci(m['em'])} | {m['unknown_rate']:.2f} | "
                         f"{'-' if ans is None else f'{ans:.2f}'} | {ci(pd) if pd else ''} |")
    cbw = summary["closed_book_wrong_subset"]["n"]
    lines += ["", f"Headline subset, questions the closed-book model gets wrong (n = {cbw}): EM per system in "
              "`results/m4/generation_dev.json` (`closed_book_wrong`).", "",
              f"Cost of this run: {summary['spend']['this_run_usd']} USD; credit left "
              f"{summary['spend']['openrouter_remaining_usd']} USD.", ""]
    return "\n".join(lines)


def main() -> None:
    s = get_settings()
    out = s.results_dir / "m4"
    out.mkdir(parents=True, exist_ok=True)
    corpus = {c["id"]: c for c in read_jsonl(s.data_dir / "corpus.jsonl")}
    questions = read_jsonl(s.data_dir / "questions_dev.jsonl") + read_jsonl(s.data_dir / "single_hop_dev.jsonl")
    test_ids = {q["id"] for f in ("questions_test.jsonl", "single_hop_test.jsonl") for q in read_jsonl(s.data_dir / f)}
    assert not test_ids & {q["id"] for q in questions}, "test questions must never be used in M4"
    accepted = json.loads((s.data_dir / "answer_aliases.json").read_text(encoding="utf-8"))
    m1 = {name: read_jsonl(s.results_dir / "m1" / f"generation_dev_{name}.jsonl") for name in ("closed_book", "hybrid")}

    # Entity embeddings: the E5 embedding of each entity's representative mention (its page mention if it
    # has one, else its first mention), reused from the M3 mention embeddings.
    mentions = build_mentions(read_jsonl(s.results_dir / "m2" / "extractions.jsonl"), corpus)
    m_emb = embed_mentions(mentions, s.embedding_model, s.cache_dir)
    m_idx = {m.id: i for i, m in enumerate(mentions)}
    encoder = E5Encoder(s.embedding_model)
    reranker = CrossEncoderReranker(s.reranker_model)
    chosen_retrieval = json.loads((s.results_dir / "m1" / "retrieval_dev.json").read_text())["chosen"]

    t0 = time.time()
    with connect(s) as driver:
        g = fetch_graph(driver)

        by_mention = {m.id: m for m in mentions}

        def rep(e):
            ids = sorted(e.mention_ids)
            pages = [i for i in ids if by_mention[i].is_page]
            return m_emb[m_idx[(pages or ids)[0]]]

        entity_emb = {eid: rep(e) for eid, e in g.entities.items()}
        indexes = {True: GraphIndex(g, entity_emb, use_exact_title=True),
                   False: GraphIndex(g, entity_emb, use_exact_title=False)}
        chunks = fetch_chunks(driver)
        dense = lambda q, k, wt: vector_search(driver, encoder.encode_queries([q])[0].tolist(), k, wt)
        hybrid = HybridRetriever(chunks, dense, reranker, HybridConfig(
            with_title=chosen_retrieval["with_title"], fusion=chosen_retrieval["fusion"], alpha=chosen_retrieval["alpha"]))

        path_cache: dict[str, np.ndarray] = {}
        retrieved = []
        for q in questions:
            q_emb = encoder.encode_queries([q["question"]])[0]
            per_index = {}
            for exact, idx in indexes.items():
                seeds = idx.seeds(q["question"], q_emb)
                paths = idx.paths([e for e, _ in seeds])
                new = [p.text for p in paths if p.text not in path_cache]
                if new:
                    for text, e in zip(new, encoder.encode_passages(new)):
                        path_cache[text] = e
                top = score_paths(paths, q_emb, np.stack([path_cache[p.text] for p in paths]), idx) if paths else []
                per_index[exact] = {"seeds": seeds, "top": top, "n_paths": len(paths)}
            retrieved.append({"q": q, "graph": per_index, "hybrid": hybrid.retrieve(q["question"], hybrid.config.rerank_top)})
    retrieval_seconds = round(time.time() - t0)

    write_jsonl(out / "graph_retrieval_dev.jsonl", [{
        "id": r["q"]["id"], "type": r["q"]["type"],
        "seeds": r["graph"][True]["seeds"], "n_paths": r["graph"][True]["n_paths"],
        "top_paths": [{"text": p.text, "score": round(p.score, 4), "sources": p.sources} for p in r["graph"][True]["top"]],
    } for r in retrieved])

    def contexts(system: str, gshare: float | None, exact: bool) -> list[PackedContext]:
        ctxs = []
        for r in retrieved:
            idx = indexes[exact]
            top = r["graph"][exact]["top"]
            if system == "graph_only":
                ctxs.append(graph_context(top, idx, corpus, BUDGET))
            else:
                ctxs.append(combine(graph_context(top, idx, corpus, int(gshare * BUDGET)), r["hybrid"], BUDGET))
        return ctxs

    llm = make_llm(s.generator_model, s)
    spent_before = ledger_totals(s)["cost_usd"]

    def run_system(name: str, ctxs: list[PackedContext]) -> list[dict]:
        def one(i):
            q, ctx = questions[i], ctxs[i]
            system_prompt, prompt = build_prompt(q["question"], ctx)
            res = llm.complete(prompt, system=system_prompt)
            pred = parse_answer(res.text)
            gold, bridge = set(q["gold_chunk_ids"]), bridge_chunks(q, corpus)
            return {"id": q["id"], "type": q["type"], "question": q["question"], "answer": q["answer"],
                    "prediction": pred, "raw": res.text, **score(pred, accepted[q["id"]]),
                    "unknown": pred.strip().lower() == "unknown", "context_chunk_ids": ctx.chunk_ids,
                    "context_tokens": ctx.tokens, "all_gold_in_context": float(gold <= set(ctx.chunk_ids)),
                    "bridge_chunks": sorted(bridge),
                    "bridge_in_context": (float(bridge <= set(ctx.chunk_ids)) if bridge else None),
                    "provider": res.provider, "input_tokens": res.input_tokens, "output_tokens": res.output_tokens,
                    "cached": res.cached}
        with ThreadPoolExecutor(WORKERS) as pool:
            rows = list(pool.map(one, range(len(questions))))
        write_jsonl(out / f"generation_dev_{name}.jsonl", rows)
        print(f"{name}: {len(rows)} answers, {sum(not r['cached'] for r in rows)} live calls", flush=True)
        return rows

    per_system = dict(m1)
    for r in per_system["hybrid"]:
        bridge = bridge_chunks(next(q for q in questions if q["id"] == r["id"]), corpus)
        r["bridge_in_context"] = float(bridge <= set(r["context_chunk_ids"])) if bridge else None
    per_system["graph_only"] = run_system("graph_only", contexts("graph_only", None, True))
    for gs in G_OPTIONS:
        per_system[f"graph_plus_chunks_g{gs}"] = run_system(f"graph_plus_chunks_g{gs}", contexts("gpc", gs, True))

    def multi(rows, key):
        vals = [r[key] for r in rows if r["type"] != "single_hop" and r.get(key) is not None]
        return sum(vals) / len(vals)

    chosen_g = min(G_OPTIONS, key=lambda gs: (-multi(per_system[f"graph_plus_chunks_g{gs}"], "em"),
                                             -multi(per_system[f"graph_plus_chunks_g{gs}"], "all_gold_in_context"), gs))
    chosen = f"graph_plus_chunks_g{chosen_g}"
    per_system[f"{chosen}_no_exact_title"] = run_system(f"{chosen}_no_exact_title", contexts("gpc", chosen_g, False))

    header = {"split": "dev", "generator": {"model": s.generator_model, "endpoint": s.generator_provider,
              "reasoning_effort": s.generator_reasoning_effort, "temperature": 0.0},
              "context_budget_tokens": BUDGET,
              "scoring": "official 2Wiki v1.1 EM/F1, max over gold answer + Wikidata aliases and demonyms"}
    summary = build_summary(per_system, header)
    hyb = {r["id"]: r for r in per_system["hybrid"]}
    retrieval = {}
    for name, rows in per_system.items():
        if name == "closed_book":
            continue
        bridge_vals = [r["bridge_in_context"] for r in rows if r["type"] != "single_hop" and r.get("bridge_in_context") is not None]
        retrieval[name] = {"multi_hop_all_gold_in_context": round(multi(rows, "all_gold_in_context"), 4),
                           "bridge_entity_recall": round(sum(bridge_vals) / len(bridge_vals), 4),
                           "bridge_questions": len(bridge_vals)}
        if name != "hybrid":
            summary["systems"][name]["paired_diff_vs_hybrid_em"] = paired_diff_ci(
                [r["em"] for r in rows], [hyb[r["id"]]["em"] for r in rows])
    summary["retrieval"] = retrieval
    summary["g_selection"] = {"options": G_OPTIONS, "chosen_g": chosen_g, "chosen_system": chosen,
                              "rule": "highest multi-hop dev EM; ties by multi-hop all-gold-in-context; then 0.25"}

    c_rows = per_system[chosen]
    target_c = [r["em"] for r in c_rows if r["type"] in TARGET_TYPES]
    target_h = [hyb[r["id"]]["em"] for r in c_rows if r["type"] in TARGET_TYPES]
    gain = retrieval[chosen]["multi_hop_all_gold_in_context"] - retrieval["hybrid"]["multi_hop_all_gold_in_context"]
    diff = summary["systems"][chosen]["paired_diff_vs_hybrid_em"]
    bar = {
        "system": chosen,
        "1_retrieval_gain": {"value": round(gain, 4), "min": BAR["retrieval_gain_min"], "pass": gain >= BAR["retrieval_gain_min"] - 1e-9},
        "2_no_qa_regression": {"paired_em_diff": diff, "ci_low_min": BAR["paired_em_ci_low_min"],
                               "pass": diff["ci_low"] >= BAR["paired_em_ci_low_min"]},
        "3_target_types_gain": {"types": list(TARGET_TYPES), "n": len(target_c),
                                "em_graph": round(sum(target_c) / len(target_c), 4), "em_hybrid": round(sum(target_h) / len(target_h), 4),
                                "em_graph_ci": mean_ci(target_c), "pass": sum(target_c) > sum(target_h)},
    }
    bar["all_pass"] = all(v["pass"] for k, v in bar.items() if k[0].isdigit())
    summary["quality_bar"] = bar
    balance = write_balance(s)
    summary["spend"] = {"this_run_usd": round(ledger_totals(s)["cost_usd"] - spent_before, 6),
                        "openrouter_remaining_usd": balance["remaining_usd"], "retrieval_seconds": retrieval_seconds}
    (out / "generation_dev.json").write_text(json.dumps(summary, indent=1, ensure_ascii=False) + "\n")
    (out / "graph_report.md").write_text(render_report(summary), encoding="utf-8")
    print(json.dumps({"retrieval": retrieval, "g_selection": summary["g_selection"], "quality_bar": bar,
                      "spend": summary["spend"]}, indent=1, ensure_ascii=False))


if __name__ == "__main__":
    main()
